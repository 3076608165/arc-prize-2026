"""Package agi2/arclib + your solver into a single self-contained Kaggle notebook.

ARC-AGI-2 is a code competition with **no internet access**, so the notebook
cannot pip-install or clone anything. This script inlines every module in
``arclib`` as one cell, then appends the driver cell that reads the hidden test
challenges and writes ``submission.json``.

    python agi2/build_notebook.py                  # -> agi2/out/submission.ipynb
    python agi2/build_notebook.py --self-test      # also verify it runs locally
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE / "arclib"

# Order matters: no module may reference one that has not been inlined yet.
MODULES = ["loader", "grids", "dsl", "search", "solvers", "evaluate"]

HEADER = '''\
# ==========================================================================
# ARC Prize 2026 - ARC-AGI-2
# Auto-generated by agi2/build_notebook.py -- do not edit in the Kaggle editor.
# Edit agi2/arclib/*.py locally and rebuild instead.
# ==========================================================================
from __future__ import annotations

import json, time, sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable
'''

DRIVER = '''\
# ==========================================================================
# driver
# ==========================================================================
INPUT_ROOTS = [Path("/kaggle/input"), Path("data/kaggle")]   # the latter: local dry run

def find_challenges() -> Path:
    """Locate the challenges file without hardcoding the mount path.

    Guessing `/kaggle/input/<competition-slug>/` cost a kernel run. Recurse
    instead, prefer a filename containing "test", and fall back to any
    challenges file so a mount-path surprise degrades to a wrong-split run
    rather than a crash that scores nothing.
    """
    found = []
    for root in INPUT_ROOTS:
        if root.is_dir():
            found += [p for p in root.rglob("*.json") if "challenges" in p.name.lower()]
    for pick in (lambda p: "test" in p.name.lower(), lambda p: True):
        hits = sorted(p for p in found if pick(p))
        if hits:
            return hits[0]

    for root in INPUT_ROOTS:                      # nothing: say what is there
        if root.is_dir():
            print(f"contents of {root}:")
            for p in sorted(root.rglob("*"))[:60]:
                print("   ", p)
    raise FileNotFoundError(f"no challenges json under {[str(r) for r in INPUT_ROOTS]}")

# Kaggle enforces a 12 hour wall clock. Leave headroom so a slow task can never
# cost you the whole submission -- an unfinished notebook scores nothing.
TIME_BUDGET_S = 11 * 3600
PER_TASK_BUDGET_S = 60.0

path = find_challenges()
raw = json.loads(path.read_text(encoding="utf-8"))
print(f"loaded {len(raw)} tasks from {path}")

started = time.time()
submission: dict = {}
n_fitted = 0
for i, (task_id, t) in enumerate(sorted(raw.items())):
    demos = [Pair(input=p["input"], output=p.get("output")) for p in t["train"]]
    tests = [p["input"] for p in t["test"]]
    per_test, names = [[] for _ in tests], []
    if time.time() - started < TIME_BUDGET_S:
        try:
            per_test, names = solve_task_full(demos, tests, max_depth=3)
        except Exception as e:                       # never let one task abort the run
            print(f"  {task_id}: {type(e).__name__}: {e}")
    n_fitted += bool(names)
    # A wrong-shaped guess scores the same as no guess, so fall back to echoing
    # the test input rather than emitting the 2x2 blank.
    submission[task_id] = [
        make_attempts(preds or [ti], len(tests)) for preds, ti in zip(per_test, tests)
    ]
    if (i + 1) % 50 == 0:
        print(f"  {i + 1}/{len(raw)} tasks, {time.time() - started:.0f}s")

Path("submission.json").write_text(json.dumps(submission))
print(f"wrote submission.json: {len(submission)} tasks, "
      f"a rule fitted {n_fitted} of them, {time.time() - started:.0f}s total")
'''


# Any relative import, in either the single-line or the parenthesised form, at
# any indentation -- `solve_task_full` imports `search` lazily from inside the
# function body. In the notebook every module shares one flat namespace, so all
# of these can simply go.
_REL_IMPORT = re.compile(
    r"^[ \t]*from[ \t]+\.[A-Za-z_.]*[ \t]+import[ \t]*(?:\([^)]*\)|[^\n(]*)\n",
    re.MULTILINE,
)
_STDLIB_IMPORT = re.compile(
    r"^[ \t]*(?:from[ \t]+(?:__future__|typing|collections|dataclasses|pathlib)"
    r"[ \t]+import[ \t]*(?:\([^)]*\)|[^\n(]*)|import[ \t]+[^\n]*)\n",
    re.MULTILINE,
)


def strip_module(src: str) -> str:
    """Drop imports -- the header already provides every name they bind."""
    return _STDLIB_IMPORT.sub("", _REL_IMPORT.sub("", src))


def build_source() -> str:
    parts = [HEADER]
    for m in MODULES:
        body = strip_module((LIB / f"{m}.py").read_text(encoding="utf-8"))
        parts.append(f"# ----- arclib/{m}.py " + "-" * (58 - len(m)) + "\n" + body)
    parts.append(DRIVER)
    return "\n\n".join(parts)


def to_notebook(source: str) -> dict:
    return {
        "cells": [
            {
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": source.splitlines(keepends=True),
            }
        ],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="agi2/out/submission.ipynb")
    ap.add_argument("--kernel-dir", default="",
                    help="assemble a push-ready folder here: notebook + "
                         "agi2/kernel-metadata.json (then `kaggle kernels push -p <dir>`)")
    ap.add_argument("--self-test", action="store_true",
                    help="run the generated source against the local eval split")
    args = ap.parse_args()

    source = build_source()

    if args.self_test:
        # Stage the public evaluation split in the layout the driver expects.
        from arclib.loader import AGI2_DATA  # noqa: E402

        stage = Path(tempfile.mkdtemp()) / "data" / "kaggle"
        stage.mkdir(parents=True)
        tasks = {
            p.stem: json.loads(p.read_text(encoding="utf-8"))
            for p in sorted((AGI2_DATA / "evaluation").glob("*.json"))
        }
        for t in tasks.values():
            for p in t["test"]:
                p.pop("output", None)
        (stage / "arc-agi_test_challenges.json").write_text(json.dumps(tasks))
        # Execute the way a notebook cell does -- via exec() in a namespace
        # with no `__file__` -- not as a script. Running it as a script hides
        # every module-level `Path(__file__)`, which is exactly the bug class
        # that only shows up once Kaggle runs the kernel.
        script = stage.parent.parent / "nb.py"
        script.write_text(source, encoding="utf-8")
        runner = stage.parent.parent / "run_as_cell.py"
        runner.write_text(
            "import pathlib\n"
            "src = pathlib.Path('nb.py').read_text(encoding='utf-8')\n"
            "exec(compile(src, '<cell>', 'exec'), {'__name__': '__main__'})\n",
            encoding="utf-8",
        )
        r = subprocess.run(
            [sys.executable, str(runner)], cwd=script.parent,
            capture_output=True, text=True,
        )
        print(r.stdout[-2000:] or r.stderr[-2000:])
        if r.returncode != 0:
            print("SELF-TEST FAILED")
            return 1
        sub = json.loads((script.parent / "submission.json").read_text())
        assert set(sub) == set(tasks), "task ids do not round-trip"
        print(f"SELF-TEST OK: {len(sub)} tasks, valid shape")

    out = Path(args.kernel_dir) / "submission.ipynb" if args.kernel_dir else Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(to_notebook(source), indent=1), encoding="utf-8")
    print(f"wrote {out}  ({len(source.splitlines())} source lines)")

    if args.kernel_dir:
        meta = HERE / "kernel-metadata.json"
        target = Path(args.kernel_dir) / "kernel-metadata.json"
        target.write_text(meta.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"wrote {target}")
        print(f"\npush it with:\n  kaggle kernels push -p {args.kernel_dir}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(HERE))
    raise SystemExit(main())
